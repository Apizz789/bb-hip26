// Generates src/i18n/dictionary.ts from the translation object `const S` in the
// original HTML prototype. The prototype stays the source of truth: re-run this
// script whenever its copy is edited, so no strings are retyped by hand.
import { readFileSync, writeFileSync } from 'node:fs';

// Default: the Phase 1-4 reference prototype (339 keys). ../preview.html is an older copy with 264 keys.
const [, , srcPath = '../preview_p4.html', outPath = 'src/i18n/dictionary.ts'] = process.argv;
const src = readFileSync(srcPath, 'utf8');
const start = src.indexOf('  const S = {');
if (start < 0) throw new Error('Could not find "const S" in ' + srcPath);
const end = src.indexOf('\n  };', start) + '\n  };'.length - 1;
const literal = src.slice(start + '  const S = '.length, end);
const S = new Function('return ' + literal)();

const lines = Object.entries(S).map(([key, [th, en]]) =>
  `  ${JSON.stringify(key)}: [${JSON.stringify(th)}, ${JSON.stringify(en)}],`);

const out = `// AUTO-GENERATED by scripts/generate-dictionary.mjs from the HTML prototype.
// Do not edit by hand. Tuple order: [Thai, English]. Thai is the default language.
export const dictionary = {
${lines.join('\n')}
} as const satisfies Record<string, readonly [string, string]>;

export type TranslationKey = keyof typeof dictionary;
`;
writeFileSync(outPath, out, 'utf8');
console.log(`Wrote ${Object.keys(S).length} keys to ${outPath}`);
